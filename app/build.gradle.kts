// Composition root shared by every platform: DI graph, logger setup, app shell and navigation host.
// The platform hosts (androidApp, desktopApp, webApp, iosApp) only start it.

plugins {
    id("convention.kmp.compose.library")
    alias(libs.plugins.buildKonfig)
}

buildkonfig {
    packageName = Namespaces.App
    defaultConfigs {
        buildConfigField(Type.STRING, "APP_NAME", appIdentity.name)
    }
}

kotlin {
    android {
        namespace = Namespaces.App
    }

    // The iOS app links this module as the static "Shared" framework (imported from Swift as `Shared`)
    targets.withType<KotlinNativeTarget>().configureEach {
        binaries.framework {
            baseName = "Shared"
            isStatic = true
            binaryOption("bundleId", "${appIdentity.applicationId}.shared")
        }
    }

    sourceSets {
        commonMain.dependencies {
            implementation(projects.data.repositoryImpl)
            implementation(projects.data.sources)
            implementation(projects.data.sourcesImpl.local)
            implementation(projects.data.sourcesImpl.remote)

            implementation(projects.domain.model)
            implementation(projects.domain.repository)
            implementation(projects.domain.useCase)

            implementation(projects.presentation.analytics)
            implementation(projects.presentation.common)
            implementation(projects.presentation.features.advert)
            implementation(projects.presentation.features.home)

            implementation(libs.kermit)
        }
        androidMain.dependencies {
            implementation(project.dependencies.platform(libs.google.firebase.bom))
            implementation(libs.google.firebase.crashlytics)
        }
        jvmTest.dependencies {
            implementation(libs.koin.test)
            implementation(libs.ktor.client.core)
        }
    }
}

// iOS reads the app identity from gradle.properties through this generated xcconfig
// (included by iosApp/Configuration/Config.xcconfig). Xcode regenerates it on every build through
// embedAndSignAppleFrameworkForXcode; after changing app.* run it once by hand so Xcode sees it.
val syncAppIdentity = tasks.register("syncAppIdentity") {
    group = "build setup"
    description = "Writes the app identity of gradle.properties to iosApp/Configuration/Identity.xcconfig"
    val identity = appIdentity
    val content = """
        |// Generated by `./gradlew syncAppIdentity` from the app.* properties of gradle.properties. Do not edit.
        |PRODUCT_NAME=${identity.compactName}
        |APP_DISPLAY_NAME=${identity.name}
        |PRODUCT_BUNDLE_IDENTIFIER=${identity.applicationId}
        |MARKETING_VERSION=${identity.versionName}
        |CURRENT_PROJECT_VERSION=${identity.versionCode}
        |""".trimMargin()
    val output = isolated.rootProject.projectDirectory.file("iosApp/Configuration/Identity.xcconfig")
    inputs.property("content", content)
    outputs.file(output)
    doLast { output.asFile.writeText(content) }
}

tasks.matching { it.name == "embedAndSignAppleFrameworkForXcode" }.configureEach { dependsOn(syncAppIdentity) }
